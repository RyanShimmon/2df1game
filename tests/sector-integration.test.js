import test from 'node:test';
import assert from 'node:assert/strict';
import {Race,TRACK,selectTrack} from '../src/core.js';
import {createWeekend,QualifyingRun,recordLap,finishQualifyingStage,nextQualifyingSession} from '../src/weekend.js';
import {newCareer} from './career-fixture.js';
import {driveQualifyingOuting} from './qualifying-driver.js';
const profile={driverName:'Sector tester',teamIndex:2};
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-6,`${a} != ${b}`);
test.afterEach(()=>selectTrack('northline'));
for(const track of ['dunes','crossover','metro'])test(`${track}: a complete race times all three sectors including the finish`,()=>{
 const r=new Race({track,laps:3,raceFormat:'sprint',fuel:6,tyre:'M',weather:'dry',aiSeed:42});
 const c=r.player;r.cars=[c];c.player=false;r.countdown=0;
 for(let i=0;i<60*300&&!r.done;i++)r.step(1/60);
 assert.ok(r.done&&!c.dnf);assert.equal(c.sectorTiming.sequence,9);
 assert.ok(c.sectorTiming.bars.every(b=>b.time>0));
 assert.equal(c.sectorTiming.active,null);assert.equal(r.sectors.fastestLap.driverId,c.id);
 near(r.sectors.fastestLap.time,c.bestLap);
 near(c.sectorTiming.bars.reduce((sum,b)=>sum+b.time,0),c.lastLap);
 assert.ok(c.bestLap>20&&c.bestLap<70);
});
test('qualifying clocks only timed laps, keeps session records through garage work, and resets for Q2 and race',()=>{
 const career=newCareer(profile),w=createWeekend(career,{track:'aurora',tyre:'S',laps:24,fuel:28,weather:'dry',aiSeed:42});
 w.setup.track='aurora';career.upgrades.aero=1;
 const q=new QualifyingRun(w,'S1',career.upgrades,profile);q.cars=[q.player];
 assert.equal(q.player.sectorTiming.active,null);
 driveQualifyingOuting(q);
 const p=q.player;
 assert.ok(p.garage&&p.qLaps===1);assert.equal(p.sectorTiming.sequence,3);
 assert.equal(p.sectorTiming.active,null);assert.ok(p.sectorTiming.bars.every(b=>b.time>0));
 near(p.sectorTiming.bars.reduce((sum,b)=>sum+b.time,0),p.lastLap);
 near(q.sectors.fastestLap.time,p.bestLap);
 const saved=JSON.parse(JSON.stringify(w)),again=new QualifyingRun(saved,p.tyreSet.id,career.upgrades,profile);
 near(again.player.bestLap,p.bestLap);assert.deepEqual(again.sectors,q.sectors);
 for(const id of w.active)recordLap(w,id,id===21?20:30+id*.01,id);
 w.elapsed=9999;finishQualifyingStage(w,career.upgrades,profile);
 const next=nextQualifyingSession(q,career.upgrades,profile);
 assert.equal(next.sectors.name,'Q2');assert.equal(next.sectors.fastestLap,null);
 assert.ok(next.sectors.bestSectors.every(s=>s===null));assert.ok(w.sectorSessions.Q1.fastestLap);
 const race=new Race(w.setup,career.upgrades,'career',profile);
 assert.equal(race.sectors.name,'Race');assert.equal(race.sectors.fastestLap,null);
});
