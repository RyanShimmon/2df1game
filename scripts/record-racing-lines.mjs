import {writeFileSync} from 'node:fs';
import {Race, TRACK, CIRCUITS, brakingDeceleration} from '../src/core.js';
import {AERO_PACKAGES, UPGRADES} from '../src/development.js';
import {guideDistances} from '../src/driving-guide.js';

import {consolidateBraking} from './guide-braking.mjs';

const dt=1/60;
const upgrades=Object.fromEntries(Object.entries(UPGRADES).map(([id,part])=>[id,part.max]));
const round=n=>Math.round(n*10)/10;

function recordPackage(track,aeroSpec){
  const race=new Race({track,laps:12,tyre:'S',fuel:2,weather:'dry',difficulty:'expert',aiSeed:42,tyreTemperatureEnabled:false});
  const car=race.cars[0];
  race.cars=[car];race.traffic=[];race.qualifying=true;
  Object.assign(car,{tyre:'S',aeroSpec,upgrades,qState:'timed',qStart:0,fuel:3,wear:0});
  car.ai.nextDecision=Infinity; // Hold the same expert driver at clean-lap pace.
  const distances=guideDistances(TRACK);
  let nextLap=0,nextSample=0,start=null,points=[],samples=[],best=null;
  const laps=[];
  let brake=0,onThrottle=0,elapsed=0,capacity=0,brakeLoss=0,brakeForce=0;
  function collect(duration){
    brake+=car.ai.brakeApplied*duration;
    capacity+=brakeForce*duration;
    brakeLoss+=brakeForce*car.ai.brakeApplied*duration;
    if(car.throttleApplied>0)onThrottle+=duration;
    elapsed+=duration;
  }
  // The first crossing after one full warm-up lap starts the first flyer.
  let line=TRACK.length;
  for(let frame=0;frame<60*360 && laps.length<3;frame++){
    const {x,y,s}=car;
    brakeForce=brakingDeceleration(car);
    race.time+=dt;race.stepAI(car,dt);
    if(car.s<=s)continue;
    // Interpolate both the clock and position where the car crosses each mark.
    let previousFraction=0;
    while(line<=car.s){
      const fraction=(line-s)/(car.s-s);
      collect((fraction-previousFraction)*dt);
      previousFraction=fraction;
      const at=race.time-dt+fraction*dt;
      // Average the controls over this stretch. Short speed corrections at
      // the apex should not speckle a sustained braking or lift zone.
      const input=brake>.12*elapsed ? 'B' : onThrottle>.5*elapsed ? 'A' : 'L';
      const sample={duration:elapsed,capacity,brakeLoss,throttling:onThrottle>.5*elapsed,speed:car.speed};
      brake=0;onThrottle=0;elapsed=0;capacity=0;brakeLoss=0;
      if(nextSample===0){
        if(start!==null){
          if(car.qInvalid || car.fuel<=0)throw Error(track+' '+aeroSpec+' invalid reference lap');
          points[0][2]=input; // segment approaching the line on this lap
          samples[0]=sample;
          const seconds=at-start;
          laps.push(seconds);
          if(!best || seconds<best.seconds)best={seconds,points,samples};
        }
        start=at;points=[];samples=[];car.qInvalid=false;car.qStart=at;
        car.fuel=1.5;car.wear=0;car.wheelWear.fill(0);
        nextLap++;
      }
      samples.push(sample);
      points.push([round(x+(car.x-x)*fraction),round(y+(car.y-y)*fraction),input]);
      nextSample=(nextSample+1)%distances.length;
      line=(nextSample===0 ? nextLap+1 : nextLap)*TRACK.length+distances[nextSample];
    }
    collect((1-previousFraction)*dt);
  }
  if(laps.length!==3)throw Error(track+' '+aeroSpec+' incomplete');
  return {...best,laps:laps.map(n=>+n.toFixed(4))};
}

const circuits={};
for(const circuit of CIRCUITS){
  const packages=Object.fromEntries(Object.keys(AERO_PACKAGES).map(spec=>[spec,recordPackage(circuit.id,spec)]));
  const [aero,best]=Object.entries(packages).sort((a,b)=>a[1].seconds-b[1].seconds)[0];
  consolidateBraking(best.points,best.samples);
  circuits[circuit.id]={aero,seconds:+best.seconds.toFixed(4),laps:Object.fromEntries(Object.entries(packages).map(([spec,result])=>[spec,result.laps])),points:best.points};
  console.log(circuit.name,aero,best.seconds.toFixed(3),[...new Set(best.points.map(p=>p[2]))].join(''));
}
const output='// Generated by node scripts/record-racing-lines.mjs\nexport const drivingReferences = {\n'+
  Object.entries(circuits).map(([id,data])=>'  '+JSON.stringify(id)+':'+JSON.stringify(data)).join(',\n')+'\n};\n';
writeFileSync(new URL('../src/driving-references.js',import.meta.url),output);
